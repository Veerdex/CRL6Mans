/* 7-team Double Elimination, played to completion, drawn with the layout math
   from app/dashboard/season/bracket-display.tsx and viewed through the fixed
   580px window from bracket-canvas.tsx.

   The rows come from /de7-data.js, which the DE7 simulator generated by running
   the real routing helpers — so the bracket below is the bracket production
   would hold for 7 teams, byes and all, rather than a hand-authored finish.

   What this page is for: the card format agreed in matchup-preview.html is
   210x100, up from 210x68. BASE_SLOT, which decides how far apart two cards in
   a round sit, is a separate constant — and `top = center - MATCH_H/2 - 16`
   spends 16px of each slot on the label row above the card. Raise MATCH_H
   without raising BASE_SLOT and the cards eat the labels. The "Layout math"
   table reports that for whichever step is selected. */

