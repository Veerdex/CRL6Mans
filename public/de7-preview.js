function isoFor(k) { return new Date(Date.now() - ELAPSED[k].secs * 1000).toISOString(); }

// ── app/lib/match-live.ts, verbatim ──────────────────────────────────────────

function formatElapsed(started, now) {
  const total = Math.max(0, Math.floor((now - new Date(started).getTime()) / 1000));
  const s = total % 60;
  const m = Math.floor(total / 60) % 60;
  const h = Math.floor(total / 3600);
  const ss = String(s).padStart(2, "0");
  return h > 0 ? h + ":" + String(m).padStart(2, "0") + ":" + ss : m + ":" + ss;
}
function isMatchLive(m) {
  return !!m.started_at && m.status === "scheduled" && m.home_score === null && m.away_score === null;
}

// ── bracket-display.tsx getMatchState ────────────────────────────────────────

function getMatchState(m) {
  const hasScores = m.home_score !== null && m.away_score !== null;
  const homeSet = m.home_team_id !== null;
  const awaySet = m.away_team_id !== null;
  if (hasScores && (!homeSet || !awaySet)) return "bye";
  if (hasScores) return "completed";
  if (isMatchLive(m)) return "live";
  if (homeSet && awaySet) return "ready";
  if (homeSet || awaySet) return "waiting";
  return "pending";
}

// bracket-display.tsx deLabelSlot, reduced to the branches this dataset reaches:
// a named team, a slot whose feeder was a bye, and the untriggered GF reset.
function slotText(m, slot) {
  const id = slot === "home" ? m.home_team_id : m.away_team_id;
  if (id) return D.teams[id].name;
  if (m.home_score !== null || m.away_score !== null) return "BYE";
  if (m.stage === GF && m.match_number === 2) return slot === "home" ? "WB Team" : "LB Team";
  return "TBD";
}

// ── Layout, copied from bracket-display.tsx ──────────────────────────────────

const matchCenter   = (r, m, SLOT) => SLOT * Math.pow(2, r - 1) * (m - 0.5);
const matchCenterLB = (r, m, SLOT) => SLOT * Math.pow(2, Math.ceil(r / 2) - 1) * (m - 0.5);
const cardTop = (center, H) => center - H / 2 - LABEL_RESERVE;

function getLBRoundName(roundNum, totalRounds) {
  const fromEnd = totalRounds - roundNum;
  if (fromEnd === 0) return "LB Finals";
  if (fromEnd === 1) return "LB Semis";
  if (fromEnd === 2) return "LB Quarters";
  return "LB Round " + roundNum;
}

// ── Data for the current selection ───────────────────────────────────────────

function rows() {
  const out = D.finishes[finish].map((m) => ({ ...m, started_at: null }));
  if (showLive) {
    // The match that decided it, rewound to the moment both captains checked in.
    const target = finish === "sweep"
      ? out.find((m) => m.stage === GF && m.match_number === 1)
      : out.find((m) => m.stage === GF && m.match_number === 2);
    Object.assign(target, { home_score: null, away_score: null, status: "scheduled", started_at: startedAt });
  }
  return out;
}

function logoFor(id) {
  const t = D.teams[id];
  if (!t) return null;
  return t.logo_url || (allCrests ? crestFor(t) : null);
}
// A neutral stand-in for the three teams that have no crest, so the "all 7" case
// can be compared without pretending those rows ship a logo today.
function crestFor(t) {
  const hues = [12, 48, 96, 160, 200, 260, 310];
  return "data:image/svg+xml;utf8," + encodeURIComponent(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">' +
    '<rect width="24" height="24" fill="hsl(' + hues[t.seed - 1] + ' 55% 42%)"/>' +
    '<path d="M12 4 20 8v5c0 4-3.4 6.4-8 7-4.6-.6-8-3-8-7V8z" fill="rgba(255,255,255,.22)"/></svg>'
  );
}

// ── Rendering ────────────────────────────────────────────────────────────────

function teamRow(m, slot, state) {
  const S = STEPS[step];
  const id = slot === "home" ? m.home_team_id : m.away_team_id;
  const score = slot === "home" ? m.home_score : m.away_score;
  const completed = state === "completed";
  const homeWon = completed && (m.home_score ?? 0) > (m.away_score ?? 0);
  const awayWon = completed && (m.away_score ?? 0) > (m.home_score ?? 0);
  const won = slot === "home" ? homeWon : awayWon;
  const faded = !id || (completed && !won);

  const url = id ? logoFor(id) : null;
  const mark = !id
    ? '<div class="dot empty"></div>'
    : url
      ? '<img class="logo' + (faded ? " faded" : "") + '" alt="" src="' + url + '" />'
      : '<div class="dot"></div>';

  const label = slotText(m, slot);
  const cls = id
    ? (won ? "tname won" : completed ? "tname lost" : "tname")
    : "tname feeder";

  return '<div class="teamrow' + (won ? " won" : "") + '"' +
    (S.row ? ' style="height:' + S.row + 'px"' : "") + ">" +
    mark + '<span class="' + cls + '">' + esc(label) + "</span>" +
    (completed && score !== null ? '<span class="score' + (won ? " won" : "") + '">' + score + "</span>" : "") +
    "</div>";
}

function card(m, state, extraClass) {
  const S = STEPS[step];
  const s = STATE[state];
  // DEMatchBox: an untriggered GF reset overrides the state palette entirely.
  const inactive = m.stage === GF && m.match_number === 2 && m.home_team_id === null;
  const style = inactive
    ? "border-color:rgba(39,39,42,.3);background:rgba(24,24,27,.1);opacity:.5"
    : "border-color:" + s.border + ";background:" + s.bg + ";box-shadow:" + s.shadow;
  return '<div class="card ' + (extraClass || "") + '" style="width:' + MATCH_W + "px;height:" + S.H + "px;" + style + '">' +
    teamRow(m, "home", state) + '<div class="divider"></div>' + teamRow(m, "away", state) + "</div>";
}

function clockHTML() {
  return '<span class="clock" data-clock>' + formatElapsed(startedAt, Date.now()) + "</span>";
}

// bracket-display.tsx StateLabel plus the id badge beside it.
function labelRow(m, state, badge) {
  const s = STATE[state];
  return '<div class="cardlabel">' +
    (badge ? '<span class="idbadge">' + esc(badge) + "</span>" : "") +
    '<span class="st" style="color:' + s.fg + '">' + s.label + "</span>" +
    (state === "live" && m.started_at ? clockHTML() : "") +
    "</div>";
}

function positioned(m, state, badge, top) {
  return '<div class="abs" style="top:' + top + 'px">' + labelRow(m, state, badge) + card(m, state) + "</div>";
}

function pairConnectors(roundMatches, centerFn, bracketH) {
  const mid = CONN_W / 2;
  let g = "";
  for (const m of roundMatches.filter((x) => x.match_number % 2 === 1)) {
    const m2 = roundMatches.find((x) => x.match_number === m.match_number + 1);
    if (!m2) continue;
    const y1 = centerFn(m.match_number), y2 = centerFn(m2.match_number), yMid = (y1 + y2) / 2;
    g += '<g stroke="#3f3f46" stroke-width="1.5" fill="none">' +
      '<line x1="0" y1="' + y1 + '" x2="' + mid + '" y2="' + y1 + '" />' +
      '<line x1="0" y1="' + y2 + '" x2="' + mid + '" y2="' + y2 + '" />' +
      '<line x1="' + mid + '" y1="' + y1 + '" x2="' + mid + '" y2="' + y2 + '" />' +
      '<line x1="' + mid + '" y1="' + yMid + '" x2="' + CONN_W + '" y2="' + yMid + '" /></g>';
  }
  return '<svg class="conn" width="' + CONN_W + '" height="' + bracketH + '" style="margin-top:' + HEAD_H + 'px">' + g + "</svg>";
}

function straightConnectors(roundMatches, centerFn, bracketH) {
  let g = "";
  for (const m of roundMatches) {
    const y = centerFn(m.match_number);
    g += '<line x1="0" y1="' + y + '" x2="' + CONN_W + '" y2="' + y + '" stroke="#3f3f46" stroke-width="1.5" />';
  }
  return '<svg class="conn" width="' + CONN_W + '" height="' + bracketH + '" style="margin-top:' + HEAD_H + 'px">' + g + "</svg>";
}

function section(all, kind) {
  const S = STEPS[step];
  const mine = all.filter((m) => m.stage === (kind === "winners" ? WB : LB));
  const numR1 = mine.filter((m) => m.round === 1).length;
  const bracketH = S.SLOT * numR1;
  const roundNums = [...new Set(mine.map((m) => m.round))].sort((a, b) => a - b);
  const totalRounds = roundNums.length;
  const prefix = kind === "winners" ? "W" : "L";
  const labelMap = kind === "winners" ? D.labels.wb : D.labels.lb;

  let html = "";
  roundNums.forEach((r, rIdx) => {
    const roundMatches = mine.filter((m) => m.round === r);
    const isLast = rIdx === roundNums.length - 1;
    const centerFn = (mn) => kind === "winners" ? matchCenter(r, mn, S.SLOT) : matchCenterLB(r, mn, S.SLOT);
    const roundName = kind === "winners"
      ? D.roundNames.wb[r]
      : getLBRoundName(r, totalRounds);

    let cards = "";
    for (const m of roundMatches) {
      const state = getMatchState(m);
      const badge = state === "bye" ? null : labelMap[r + "-" + m.match_number];
      cards += positioned(m, state, badge, cardTop(centerFn(m.match_number), S.H));
    }

    // bracket-display.tsx: pairs feed forward in the WB and in even LB rounds;
    // odd LB rounds just carry a team across, and the last round feeds nothing.
    const conn = isLast ? ""
      : kind === "winners" || r % 2 === 0
        ? pairConnectors(roundMatches, centerFn, bracketH)
        : straightConnectors(roundMatches, centerFn, bracketH);

    html += '<div class="col"><div class="rcol" style="width:' + MATCH_W + 'px">' +
      '<div class="rhead"><span>' + esc(roundName) + "</span></div>" +
      '<div class="rbody">' + cards + "</div></div>" + conn + "</div>";
  });

  // The Grand Final columns are appended to the winners bracket, and centred on
  // the winners bracket's height — not their own.
  if (kind === "winners") {
    const gfMain = all.find((m) => m.stage === GF && m.match_number === 1);
    const gfReset = all.find((m) => m.stage === GF && m.match_number === 2);
    const gfCenterY = bracketH / 2;
    const gfTop = cardTop(gfCenterY, S.H);
    const line = '<svg class="conn" width="' + CONN_W + '" height="' + bracketH + '" style="margin-top:' + HEAD_H + 'px">' +
      '<line x1="0" y1="' + gfCenterY + '" x2="' + CONN_W + '" y2="' + gfCenterY + '" stroke="#3f3f46" stroke-width="1.5" /></svg>';

    html += line + '<div class="rcol" style="width:' + MATCH_W + 'px">' +
      '<div class="rhead"><span>Grand Final</span></div>' +
      '<div class="rbody">' + positioned(gfMain, getMatchState(gfMain), "GF", gfTop) + "</div></div>";

    const resetActive = gfReset.home_team_id !== null;
    const resetState = getMatchState(gfReset);
    html += line + '<div class="rcol' + (resetActive ? "" : " inactive") + '" style="width:' + MATCH_W + 'px">' +
      '<div class="rhead"><span>' + (resetActive ? "GF Reset" : "GF Reset (if needed)") + "</span></div>" +
      '<div class="rbody"><div class="abs" style="top:' + gfTop + 'px">' +
      (resetActive
        ? labelRow(gfReset, resetState, "GF Reset")
        : '<div class="cardlabel"><span class="idbadge">GF Reset</span>' +
          '<span class="st" style="color:var(--zinc-600)">IF NEEDED</span></div>') +
      card(gfReset, resetState) + "</div></div></div>";
  }

  return '<div class="sec"><h3 class="sectitle">' +
    (kind === "winners" ? "Winners Bracket" : "Losers Bracket") + "</h3>" +
    '<div class="secbody" style="height:' + (bracketH + HEAD_H) + 'px">' + html + "</div></div>";
}

function render() {
  const S = STEPS[step];
  const all = rows();

  el("content").className = "content" + (step === "port" ? " port" : "") +
    (step === "port" && stretchDot ? " stretchdot" : "");
  el("content").innerHTML = section(all, "winners") + section(all, "losers");

  el("legend").innerHTML = LEGEND.map(([k, name]) =>
    '<div class="item"><span class="sw" style="border-color:' + STATE[k].border + ";background:" + STATE[k].bg +
    '"></span><span>' + name + "</span></div>").join("");

  for (const [k, cfg] of Object.entries(STEPS))
    el("step-" + k).setAttribute("aria-pressed", String(k === step));
  for (const k of Object.keys(FINISHES))
    el("fin-" + k).setAttribute("aria-pressed", String(k === finish));
  for (const k of Object.keys(ELAPSED))
    el("ela-" + k).setAttribute("aria-pressed", String(k === elapsedKey));
  ZOOMS.forEach((z, i) => el("z" + i).setAttribute("aria-pressed", String(Math.abs(pan.scale - z) < 0.001)));

  el("elapsed").style.opacity = showLive ? "1" : ".4";
  el("stretchDotLabel").className = "check" + (step === "port" ? "" : " off");
  el("stretchDot").disabled = step !== "port";

  applyPan();
  readout(all, S);
}

function applyPan() {
  el("cvinner").style.transform = "translate(" + pan.x + "px," + pan.y + "px) scale(" + pan.scale + ")";
  const cv = el("canvas");
  cv.style.backgroundSize = (24 * pan.scale) + "px " + (24 * pan.scale) + "px";
  cv.style.backgroundPosition = pan.x + "px " + pan.y + "px";
  el("zlabel").textContent = Math.round(pan.scale * 100) + "%";
}

// ── The readout ──────────────────────────────────────────────────────────────
// Each card occupies [top, top + labelRow + MATCH_H]. The label row is measured
// off the rendered DOM rather than assumed, because Tailwind's arbitrary
// text-[10px] sets no line-height of its own and the badge adds py-0.5.

// The tallest row, not the first: the first one in the DOM is W-A, which is a
// bye and so carries no id badge — and it is the badge's padding that decides
// how much vertical space the label row actually takes.
function labelRowHeight() {
  let tallest = 0;
  for (const node of el("content").querySelectorAll(".cardlabel")) {
    const mb = parseFloat(getComputedStyle(node).marginBottom) || 0;
    tallest = Math.max(tallest, node.offsetHeight + mb);
  }
  return tallest;
}

function colGeometry(name, centers, S, labelH, bodyH) {
  const blocks = centers.map((c) => {
    const top = cardTop(c, S.H);
    return { top, bottom: top + labelH + S.H };
  }).sort((a, b) => a.top - b.top);

  let minGap = null;
  for (let i = 1; i < blocks.length; i++) {
    const gap = blocks[i].top - blocks[i - 1].bottom;
    if (minGap === null || gap < minGap) minGap = gap;
  }
  return {
    name,
    firstTop: blocks[0].top,
    minGap,
    over: Math.max(...blocks.map((b) => b.bottom)) - bodyH,
  };
}

function readout(all, S) {
  const labelH = labelRowHeight();
  const numR1WB = D.numR1WB, numR1LB = D.numR1LB;
  const wbH = S.SLOT * numR1WB, lbH = S.SLOT * numR1LB;
  const lines = [];

  for (let r = 1; r <= D.numWB; r++) {
    const ms = all.filter((m) => m.stage === WB && m.round === r);
    lines.push(colGeometry("WB R" + r, ms.map((m) => matchCenter(r, m.match_number, S.SLOT)), S, labelH, wbH));
  }
  lines.push(colGeometry("Grand Final", [wbH / 2], S, labelH, wbH));
  lines.push({ sep: true });
  for (let r = 1; r <= D.numLB; r++) {
    const ms = all.filter((m) => m.stage === LB && m.round === r);
    lines.push(colGeometry("LB R" + r, ms.map((m) => matchCenterLB(r, m.match_number, S.SLOT)), S, labelH, lbH));
  }

  const cell = (v, bad, warn) =>
    '<td class="' + (bad ? "bad" : warn ? "warn" : "") + '">' + v + "</td>";

  el("geo").innerHTML =
    "<tr><th>Column</th><th>1st top</th><th>Min gap</th><th>Spill</th></tr>" +
    lines.map((g) => g.sep ? '<tr class="sep"><td colspan="4"></td></tr>' :
      "<tr>" + "<td>" + g.name + "</td>" +
      cell(g.firstTop, g.firstTop < 0) +
      (g.minGap === null ? "<td>&mdash;</td>" : cell(g.minGap, g.minGap < 0, g.minGap < 6)) +
      cell(g.over > 0 ? "+" + g.over : 0, false, g.over > 0) +
      "</tr>").join("");

  // The canvas is a fixed 580px window. The whole bracket overflows it at every
  // step, today included — but the winners bracket on its own currently fits,
  // and that is what the port costs.
  const contentH = el("content").offsetHeight;
  const wbBlockH = wbH + HEAD_H + 38; // + section title, its gap, and the canvas's own padding
  const real = lines.filter((g) => !g.sep);
  const overlaps = real.filter((g) => g.minGap !== null && g.minGap < 0);
  const intrudes = real.filter((g) => g.firstTop < 0);
  const spills = real.filter((g) => g.over > 0);
  const deadSpace = S.row !== null ? S.H - (S.row * 2 + 1) - 2 : 0;

  const finds = [];
  if (intrudes.length)
    finds.push("<b>" + intrudes.length + " column" + (intrudes.length > 1 ? "s" : "") + " start above the round header</b> (top " +
      intrudes[0].firstTop + "px), so the first card's label row is drawn over the round name.");
  if (overlaps.length)
    finds.push("<b>" + overlaps.length + " column" + (overlaps.length > 1 ? "s" : "") + " overlap</b> by up to " +
      Math.abs(Math.min(...overlaps.map((g) => g.minGap))) + "px &mdash; a card covers the label of the one below it.");
  if (spills.length)
    finds.push(spills.length + " column" + (spills.length > 1 ? "s" : "") + " spill up to " +
      Math.max(...spills.map((g) => g.over)) + "px past <code>bracketH</code>.");
  if (deadSpace > 4)
    finds.push("<b>" + deadSpace + "px of dead space</b> under the two rows: they are pinned at <code>height: " +
      S.row + "</code> in four places and don't grow with the card.");

  const clean = !finds.length;
  if (clean) finds.push("No collisions. Every column keeps its label row, at today's spacing exactly.");

  // Not a collision, so it doesn't make the step unclean.
  finds.push("Winners bracket alone: <b>" + wbBlockH + "px</b> in the canvas's fixed <code>580</code> &mdash; " +
    (wbBlockH > 580 ? "<b>no longer fits</b> at 100%." : "still fits at 100%.") +
    " Whole bracket " + contentH + "px, which overflows at every step, today included.");

  el("verdict").className = "verdict" + (clean ? " ok" : "");
  el("verdict").innerHTML =
    "<b>" + STEPS[step].name + "</b> &mdash; MATCH_H " + S.H + ", BASE_SLOT " + S.SLOT +
    ", label row " + labelH + "px measured.<br />" + STEPS[step].note +
    "<ul><li>" + finds.join("</li><li>") + "</li></ul>";
}

