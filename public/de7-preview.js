// ── Pan / zoom, mirroring bracket-canvas.tsx ─────────────────────────────────

(function canvasControls() {
  const cv = el("canvas");
  let dragging = false, last = { x: 0, y: 0 };
  cv.addEventListener("mousedown", (e) => { dragging = true; last = { x: e.clientX, y: e.clientY }; cv.classList.add("grabbing"); });
  const stop = () => { dragging = false; cv.classList.remove("grabbing"); };
  cv.addEventListener("mouseup", stop);
  cv.addEventListener("mouseleave", stop);
  cv.addEventListener("mousemove", (e) => {
    if (!dragging) return;
    pan.x += e.clientX - last.x;
    pan.y += e.clientY - last.y;
    last = { x: e.clientX, y: e.clientY };
    applyPan();
  });
  cv.addEventListener("wheel", (e) => {
    e.preventDefault();
    const r = cv.getBoundingClientRect();
    const mx = e.clientX - r.left, my = e.clientY - r.top;
    const factor = e.deltaY < 0 ? 1.1 : 1 / 1.1;
    const ns = Math.min(3, Math.max(0.15, pan.scale * factor));
    pan = { x: mx - (mx - pan.x) * (ns / pan.scale), y: my - (my - pan.y) * (ns / pan.scale), scale: ns };
    applyPan();
    ZOOMS.forEach((z, i) => el("z" + i).setAttribute("aria-pressed", String(Math.abs(pan.scale - z) < 0.001)));
  }, { passive: false });
})();

